#!/usr/bin/env python3
# gen_font.py - generate font16.c (16x16 1bpp MSB-first bitmap font) from a TTF.
#
# Requires Pillow:  pip install pillow   (build container has it; PC needs it too)
# Usage:  python3 gen_font.py

from PIL import Image, ImageDraw, ImageFont
import os

TTF = "/opt/desktop-companion/openvela/contest2026_307_justdoit/app/day2_ui/fonts/MiSans-Regular.ttf"
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "font16.c")

W = H = 16
BPR = 2  # bytes per row for width 16, 1bpp, MSB-first

# ASCII first, then the Chinese glyphs.
CHARS = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789:.%-C- " + "°" + "星期一二三四五六日晴阴云雨雪雾风多无网温度" + "开始聆听正在思考说错出了"


def render(ch):
    # Draw into a large canvas so a 32px glyph is never clipped, then crop
    # to its ink bounding box and resize down to 16x16.
    canvas = Image.new("L", (64, 64), 0)
    d = ImageDraw.Draw(canvas)
    try:
        font = ImageFont.truetype(TTF, 32)
    except Exception:
        font = ImageFont.load_default()
    d.text((0, 0), ch, fill=255, font=font)
    bbox = d.textbbox((0, 0), ch, font=font)
    if bbox[2] <= bbox[0] or bbox[3] <= bbox[1]:
        return [0] * (BPR * H)  # blank (e.g. space)
    g = canvas.crop(bbox)
    g = g.resize((W, H), Image.LANCZOS)
    px = g.load()
    data = bytearray(BPR * H)
    for y in range(H):
        for x in range(W):
            if px[x, y] > 128:
                data[y * BPR + (x >> 3)] |= (0x80 >> (x & 7))
    return list(data)

glyphs = []
for ch in CHARS:
    glyphs.append((ord(ch), render(ch)))

with open(OUT, "w") as f:
    f.write("/* Auto-generated by gen_font.py from MiSans-Regular.ttf - do not edit. */\n")
    f.write('#include <stddef.h>\n')
    f.write('#include "font16.h"\n\n')
    f.write("const int FONT16_COUNT = %d;\n" % len(glyphs))
    f.write("const uint16_t font16_codes[] = {\n")
    f.write("  " + ", ".join(str(c) for c, _ in glyphs) + "\n};\n\n")
    f.write("const uint8_t font16_data[][FONT16_BPR * FONT16_H] = {\n")
    for c, data in glyphs:
        f.write("  { /* U+%04X */ " % c)
        f.write(", ".join("0x%02x" % b for b in data))
        f.write(" },\n")
    f.write("};\n\n")
    f.write("const uint8_t *font16_lookup(uint16_t code)\n")
    f.write("{\n")
    f.write("  for (int i = 0; i < FONT16_COUNT; i++)\n")
    f.write("    if (font16_codes[i] == code)\n")
    f.write("      return font16_data[i];\n")
    f.write("  return NULL;\n")
    f.write("}\n")

print("wrote", OUT, "glyphs=", len(glyphs))
